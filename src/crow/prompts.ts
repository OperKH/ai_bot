const list = (lines: string[], empty: string) => (lines.length > 0 ? lines.map((l) => `- ${l}`).join('\n') : empty);

/** What the crow said in the chat lately, each with how long ago, for a text outside an arc not to repeat it */
const memorySection = (recentPosts: string[]): string =>
  `# ЩО КАРА ВЖЕ КАЗАЛА В ЦЬОМУ ЧАТІ (\`recentPosts\`)\n\n${list(recentPosts, '- (нічого)')}`;

/** What the previous attempt got wrong, as the last section of a request; none on the first attempt */
